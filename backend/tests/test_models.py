"""Unit tests for NewsItem and API response models."""
import pytest
from pydantic import ValidationError

from backend.common.constants.categories import ESTDCategory, VALID_CATEGORIES
from backend.step1_source_collection.models.news_item import NewsItem
from backend.step1_source_collection.models.response_models import (
    CollectionResponse,
    ErrorDetail,
    ErrorResponse,
)


def test_valid_news_item_all_fields():
    """Verify NewsItem creation with all fields populated."""
    item = NewsItem(
        title="Revolutionary AI Architecture Released",
        description="A major research lab introduces a breakthrough in reasoning.",
        url="https://example.com/ai-news",
        source_name="Tech Dispatch",
        source_type="gnews",
        author="Alice Researcher",
        published_at="2026-09-30T10:00:00Z",
        category="Tech",
        image_url="https://example.com/image.jpg",
        collected_at="2026-09-30T10:05:00Z",
    )
    assert item.title == "Revolutionary AI Architecture Released"
    assert item.source_type == "gnews"
    assert item.category == "Tech"
    assert item.author == "Alice Researcher"
    assert item.image_url == "https://example.com/image.jpg"


def test_valid_news_item_optional_fields_none():
    """Verify NewsItem creation with optional fields as None."""
    item = NewsItem(
        title="Minimal News Item",
        url="https://example.com/minimal",
        source_type="newsdata",
        category="Technology",
    )
    assert item.description is None
    assert item.source_name is None
    assert item.author is None
    assert item.published_at is None
    assert item.image_url is None
    assert item.collected_at is not None  # Auto-generated by default_factory


def test_news_item_all_five_categories_valid():
    """Verify that each of the 5 official ESTD categories is accepted."""
    for category in VALID_CATEGORIES:
        item = NewsItem(
            title="Sample Headline",
            url="https://example.com/article",
            source_type="gnews",
            category=category,
        )
        assert item.category == category


def test_news_item_invalid_category_rejected():
    """Verify that unsupported category strings are rejected."""
    with pytest.raises(ValidationError) as exc_info:
        NewsItem(
            title="Invalid Category Article",
            url="https://example.com/article",
            source_type="gnews",
            category="UnrecognizedCategoryXYZ",
        )
    assert "Invalid category 'UnrecognizedCategoryXYZ'" in str(exc_info.value)


def test_news_item_empty_title_rejected():
    """Verify that an empty title string fails validation."""
    with pytest.raises(ValidationError):
        NewsItem(
            title="",
            url="https://example.com/article",
            source_type="gnews",
            category="Technology",
        )


def test_news_item_empty_url_rejected():
    """Verify that an empty URL fails validation."""
    with pytest.raises(ValidationError):
        NewsItem(
            title="Some Title",
            url="",
            source_type="gnews",
            category="Technology",
        )


def test_collection_response_serialization():
    """Verify CollectionResponse model structure and serialization."""
    item = NewsItem(
        title="Test Title",
        url="https://example.com/test",
        source_type="gnews",
        category="Technology",
    )
    resp = CollectionResponse(
        provider="gnews",
        category="Technology",
        count=1,
        items=[item],
    )
    data = resp.model_dump()
    assert data["provider"] == "gnews"
    assert data["category"] == "Technology"
    assert data["count"] == 1
    assert len(data["items"]) == 1
    assert data["items"][0]["title"] == "Test Title"


def test_error_response_serialization():
    """Verify ErrorResponse structure matches required contract."""
    err = ErrorResponse(
        error=ErrorDetail(
            code="EXTERNAL_API_ERROR",
            message="Unable to fetch news from provider.",
        )
    )
    data = err.model_dump()
    assert data["error"]["code"] == "EXTERNAL_API_ERROR"
    assert data["error"]["message"] == "Unable to fetch news from provider."
