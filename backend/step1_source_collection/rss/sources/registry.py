class RSSSourceRegistry:
    """In-memory registry managing RSS source definitions."""

    def __init__(self, initial_sources: Optional[List[RSSSource]] = None):
        self._sources: Dict[str, RSSSource] = {}
        sources = initial_sources if initial_sources is not None else DEFAULT_RSS_SOURCES
        for source in sources:
            self._sources[source.source_id] = source

    def register_source(self, source: RSSSource) -> None:
        """Add or update an RSS source in the registry."""
        self._sources[source.source_id] = source

    def get_source_by_id(self, source_id: str) -> Optional[RSSSource]:
        """Lookup an RSS source by its unique ID."""
        return self._sources.get(source_id)

    def get_source(self, source_id: str) -> Optional[RSSSource]:
        """Alias for get_source_by_id."""
        return self._sources.get(source_id)

    def get_all_sources(self, enabled_only: bool = True) -> List[RSSSource]:
        """Return all registered sources, optionally filtering for enabled ones."""
        sources = list(self._sources.values())
        if enabled_only:
            return [s for s in sources if s.enabled]
        return sources

    def get_sources_by_category(self, category: str, enabled_only: bool = True) -> List[RSSSource]:
        """Return sources belonging to a specific ESTD category (supporting canonical resolution)."""
        from backend.common.constants.categories import resolve_canonical_category
        try:
            canonical_target = resolve_canonical_category(category).lower()
        except Exception:
            canonical_target = category.strip().lower()

        matched = [s for s in self._sources.values() if s.category.lower() == canonical_target]
        if enabled_only:
            return [s for s in matched if s.enabled]
        return matched

    def get_sources_by_subcategory(self, subcategory: str, enabled_only: bool = True) -> List[RSSSource]:
        """Return sources belonging to a specific ESTD subcategory (supporting canonical resolution)."""
        from backend.common.constants.categories import resolve_subcategory
        resolved = resolve_subcategory(subcategory)
        target = resolved.lower() if resolved else subcategory.strip().lower()
        matched = [s for s in self._sources.values() if (s.subcategory or "").lower() == target]
        if enabled_only:
            return [s for s in matched if s.enabled]
        return matched


# Global registry instance
registry = RSSSourceRegistry()


def get_source_registry() -> RSSSourceRegistry:
    """Return the global RSS source registry singleton."""
    return registry
